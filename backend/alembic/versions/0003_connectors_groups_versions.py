def _record_current_text_as_version_1() -> None:
    """Every existing document gets a version 1 holding its current text."""
    bind = op.get_bind()
    # Typed table stubs, so values (dates especially) come back as Python objects on every database.
    documents = sa.table(
        "documents",
        sa.column("id", sa.Integer),
        sa.column("sha256", sa.String),
        sa.column("size", sa.Integer),
        sa.column("uploaded_by", sa.Integer),
        sa.column("created_at", sa.DateTime(timezone=True)),
    )
    chunks_t = sa.table(
        "document_chunks", sa.column("document_id", sa.Integer), sa.column("ordinal", sa.Integer), sa.column("text", sa.Text)
    )
    docs = bind.execute(
        sa.select(documents.c.id, documents.c.sha256, documents.c.size, documents.c.uploaded_by, documents.c.created_at)
    ).all()
    if not docs:
        return
    chunks: dict[int, list[str]] = {}
    for doc_id, chunk in bind.execute(
        sa.select(chunks_t.c.document_id, chunks_t.c.text).order_by(chunks_t.c.document_id, chunks_t.c.ordinal)
    ):
        chunks.setdefault(doc_id, []).append(chunk)
    versions = sa.table(
        "document_versions",
        sa.column("document_id", sa.Integer),
        sa.column("version", sa.Integer),
        sa.column("text", sa.Text),
        sa.column("sha256", sa.String),
        sa.column("size", sa.Integer),
        sa.column("change_summary", sa.Text),
        sa.column("created_by", sa.Integer),
        sa.column("created_at", sa.DateTime(timezone=True)),
    )
    op.bulk_insert(
        versions,
        [
            {
                "document_id": doc_id,
                "version": 1,
                "text": "\n\n".join(chunks.get(doc_id, [])),
                "sha256": sha,
                "size": size,
                "change_summary": "",
                "created_by": uploaded_by,
                "created_at": created_at,
            }
            for doc_id, sha, size, uploaded_by, created_at in docs
        ],
    )


